// Method: includes, isArray, indexOf, reverse, join

let friends = ["Rahim", "karim", "Jabed"];

// includes: check a value that exist or not
console.log(friends.includes("akash"));

// isArray: to check array or not
console.log(Array.isArray(friends));

// indexOf
console.log(friends.indexOf("karim"));
console.log(friends.indexOf("karima"));

// reverse
console.log(friends.reverse());

// join: to convert to string

let str = friends.join("-");
console.log(str);




